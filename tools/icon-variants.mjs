/**
 * Derives the two secondary icon variants from the ONE master SVG.
 *
 * Never hand-edit a variant: re-theming the icon must be a single command, and three
 * hand-maintained SVGs drift apart the first time anyone touches a colour.
 *
 *   node tools/icon-variants.mjs
 *
 * icon-maskable.svg  Android applies its OWN mask to a maskable icon. A baked rounded
 *                    plate inside that mask renders as a rounded square floating in a
 *                    circle, and anything near the edge is clipped. So: full-bleed
 *                    background, square corners, art shrunk into the safe zone.
 * icon-square.svg    Windows, Tauri and Steam draw their own container. A baked plate
 *                    double-rounds, so this one is transparent with the art to the edges.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DIR = join(ROOT, 'src/assets/icon');
const master = readFileSync(join(DIR, 'icon.svg'), 'utf8');

/** Android's maskable safe zone is the central 80%; 72% leaves margin for a squircle too. */
const MASKABLE_ART_SCALE = 0.72;
/** The square variant loses the plate's padding, so the art grows to use it. */
const SQUARE_ART_SCALE = 1.12;

const CENTRE = 512;
const scaleAbout = (k) => `translate(${CENTRE * (1 - k)} ${CENTRE * (1 - k)}) scale(${k})`;

/** The art is everything between the plate background and the plate bevel. */
function splitMaster(src) {
  const openBody = src.indexOf('<g clip-path="url(#plate)">');
  const bodyStart = src.indexOf('\n', openBody) + 1;
  const bevelMark = src.indexOf('<!-- ============ PLATE BEVEL');
  const head = src.slice(0, openBody);
  const body = src.slice(bodyStart, bevelMark);
  return { head, body };
}

const { head, body } = splitMaster(master);

/** The four full-canvas rects that ARE the plate, plus the grain that sits on them. */
const PLATE_RECTS =
  /\s*<rect width="1024" height="1024"[^>]*\/>\n?|\s*<rect width="1024" height="1024"[^>]*>[\s\S]*?<\/rect>\n?/g;

const artOnly = body.replace(PLATE_RECTS, '');

// ---- maskable: full bleed, square corners, art inside the safe zone -------------------
const maskable = `${head}<!--
  GENERATED by tools/icon-variants.mjs from icon.svg. Do not edit.

  MASKABLE. Android masks this itself, so the plate is gone and the background runs
  full bleed with square corners. The art is scaled to ${MASKABLE_ART_SCALE} and centred, which keeps
  every stroke inside the central 80% circle the platform guarantees.
-->
<rect width="1024" height="1024" fill="url(#plateGround)"/>
<rect width="1024" height="1024" fill="url(#violetFill)"/>
<rect width="1024" height="1024" fill="url(#keyPool)"/>
<g transform="${scaleAbout(MASKABLE_ART_SCALE)}">
${artOnly}
</g>
</svg>
`;

// ---- square: transparent, no plate, art to the edges ----------------------------------
const square = `${head}<!--
  GENERATED by tools/icon-variants.mjs from icon.svg. Do not edit.

  SQUARE. Transparent, no plate, no bevel: Windows, Tauri and Steam apply their own
  container shape and a baked plate double-rounds. Art is scaled to ${SQUARE_ART_SCALE} to reclaim the
  padding the plate used to occupy.
-->
<g transform="${scaleAbout(SQUARE_ART_SCALE)}">
${artOnly}
</g>
</svg>
`;

// ---- boot: the master, minus the filters that cost more than they show at 96px --------
//
// The boot veil paints BEFORE the renderer exists, on the same thread that is about to
// initialise Rapier's WASM and the WebGPU device. A 1024x1024 feTurbulence grain field and
// a 26px gaussian bloom are invisible at 96px and are not worth rasterising there - the
// veil's own stylesheet already refuses to animate anything but transform and opacity for
// exactly this reason.
const boot = master
  .replace(/<filter id="grain"[\s\S]*?<\/filter>/, '')
  .replace(/<filter id="bigBloom"[\s\S]*?<\/filter>/, '')
  .replace(/\s*<rect width="1024" height="1024" filter="url\(#grain\)"[^>]*\/>/, '')
  .replace(/\s*<g filter="url\(#bigBloom\)"[\s\S]*?<\/g>/, '')
  // Ids become global once this is inlined into index.html; namespace them so the icon can
  // never collide with a gradient the UI layer defines later.
  .replace(/id="([a-zA-Z0-9]+)"/g, 'id="bi-$1"')
  .replace(/url\(#([a-zA-Z0-9]+)\)/g, 'url(#bi-$1)')
  .replace(/href="#([a-zA-Z0-9]+)"/g, 'href="#bi-$1"')
  // Intrinsic width/height, NOT just a CSS class. app.css is imported from main.ts, so at
  // first paint it has not arrived yet - measured: one stylesheet at 100ms, seven at 400ms.
  // With sizing left to CSS the icon painted at its intrinsic 1024px and shoved the wordmark
  // off screen for the first frames. The attributes make the very first paint correct; the
  // clamp() in app.css then takes over and makes it responsive.
  .replace(
    '<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024"',
    '<svg class="boot__icon" aria-hidden="true" focusable="false" xmlns="http://www.w3.org/2000/svg" width="96" height="96"',
  );

writeFileSync(join(DIR, 'icon-boot.svg'), boot);
console.log('  wrote icon-boot.svg      grain + bloom stripped, ids namespaced');

// ---- inject the boot icon INLINE into index.html --------------------------------------
//
// Inline, not <img src>: the boot veil is the first paint, and a fetched icon flashes an
// empty box before it lands. That flash is the entire defect this exists to avoid.
const htmlPath = join(ROOT, 'index.html');
const html = readFileSync(htmlPath, 'utf8');
const OPEN = '<!-- ICON:BEGIN generated by tools/icon-variants.mjs - do not edit by hand -->';
const CLOSE = '<!-- ICON:END -->';
const inlined = boot.split('\n').map((l) => `        ${l}`).join('\n');
const block = `${OPEN}\n${inlined}\n        ${CLOSE}`;
if (html.includes(OPEN)) {
  const a = html.indexOf(OPEN);
  const b = html.indexOf(CLOSE) + CLOSE.length;
  writeFileSync(htmlPath, html.slice(0, a) + block.trimStart() + html.slice(b));
  console.log('  updated the inline boot icon in index.html');
} else {
  const anchor = '<p class="boot__word t-display">SHATTERPOINT</p>';
  writeFileSync(htmlPath, html.replace(anchor, `${block}\n        ${anchor}`));
  console.log('  inlined the boot icon into index.html');
}

// ---- adaptive foreground: TRANSPARENT, art inside the 72dp-of-108dp safe circle --------
//
// An adaptive icon's foreground must have nothing outside the art. Launchers scale and
// parallax the foreground and background independently, so a baked ground shows a seam
// against the background layer and doubles the plate. The shipped build had alpha 255 in
// all four corners because it was rendered from icon-maskable.svg, which paints its own
// full-bleed ground - omitBackground cannot remove a ground the SVG itself draws.
//
// The safe zone here is STRICTER than the PWA maskable rule: 108dp canvas, only the central
// 72dp guaranteed, so a radius of 33.3% of the width rather than 40%.
const ADAPTIVE_ART_SCALE = 0.60;
const foreground = `${head}<!--
  GENERATED by tools/icon-variants.mjs from icon.svg. Do not edit.

  ADAPTIVE FOREGROUND. No plate, no background, fully transparent outside the art. Scaled to
  ${ADAPTIVE_ART_SCALE} so the art stays inside the central 72dp of the 108dp canvas - the only region
  Android guarantees against an aggressive launcher mask.
-->
<g transform="${scaleAbout(ADAPTIVE_ART_SCALE)}">
${artOnly}
</g>
</svg>
`;
writeFileSync(join(DIR, 'icon-foreground.svg'), foreground);
console.log('  wrote icon-foreground.svg  transparent, art scale', ADAPTIVE_ART_SCALE);

// ---- monochrome: a single-colour silhouette the system tints itself --------------------
//
// Without one, Android 13+ themed icons fall back to an unthemed rendering and the icon
// stops matching every other icon on a Material You home screen.
const monochrome = `${head}<!--
  GENERATED by tools/icon-variants.mjs. Do not edit.

  MONOCHROME. One flat colour; the system replaces it with the user's theme tint, so only
  the SHAPE carries meaning here - the hull silhouette plus the fracture network that spells
  the mark. Nothing that relies on hue or value survives this layer, which is why the
  gradients, facets and chips are all dropped rather than flattened.
-->
<g transform="${scaleAbout(ADAPTIVE_ART_SCALE)}" fill="#000000" stroke="none">
  <polygon points="418,150 776,254 866,566 668,876 336,844 172,552 236,296"/>
</g>
<g transform="${scaleAbout(ADAPTIVE_ART_SCALE)}" fill="none" stroke="#ffffff" stroke-width="26"
   stroke-linecap="butt" stroke-linejoin="miter">
  <use href="#letters"/>
  <use href="#midRuns" stroke-width="16"/>
</g>
</svg>
`;
writeFileSync(join(DIR, 'icon-monochrome.svg'), monochrome);
console.log('  wrote icon-monochrome.svg  flat silhouette for themed icons');

writeFileSync(join(DIR, 'icon-maskable.svg'), maskable);
writeFileSync(join(DIR, 'icon-square.svg'), square);
console.log('  wrote icon-maskable.svg  art scale', MASKABLE_ART_SCALE);
console.log('  wrote icon-square.svg    art scale', SQUARE_ART_SCALE);
